function setLanguage(lang) {
  if (!Object.hasOwn(I18N, lang)) lang = "sk";
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll("[data-i18n]")) {
    const value = I18N[lang][el.dataset.i18n];
    if (value !== undefined) el.textContent = value;
  }
  for (const button of document.querySelectorAll("[data-lang]")) {
    button.setAttribute("aria-pressed", String(button.dataset.lang === lang));
  }
  for (const badge of document.querySelectorAll("[data-app-store-badge]")) {
    badge.src = `../assets/app-store-${lang}.svg`;
    badge.alt = I18N[lang][badge.dataset.appStoreBadge];
  }
  for (const link of document.querySelectorAll("[data-keep-language]")) {
    const destination = new URL(link.href);
    destination.searchParams.set("lang", lang);
    link.href = destination.href;
  }
  const url = new URL(window.location.href);
  url.searchParams.set("lang", lang);
  window.history.replaceState(null, "", url);
  try { localStorage.setItem("lang", lang); } catch (_) {}
}

let savedLanguage;
try { savedLanguage = localStorage.getItem("lang"); } catch (_) {}
const requestedLanguage = new URLSearchParams(window.location.search).get("lang");
setLanguage(Object.hasOwn(I18N, requestedLanguage) ? requestedLanguage : savedLanguage);

for (const button of document.querySelectorAll("[data-lang]")) {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
}

// Keep the download hidden until the published release manifest is available.
const deliveryDownload = document.getElementById("deliverytracker-download");
if (deliveryDownload) {
  fetch("release.json", { cache: "no-store" })
    .then(response => {
      if (!response.ok) throw new Error("Release status unavailable");
      return response.json();
    })
    .then(release => {
      if (release.available !== true || !release.version || !Number.isInteger(release.version_code)) return;
      document.getElementById("deliverytracker-version").textContent = `${release.version} (${release.version_code})`;
      document.getElementById("deliverytracker-version-date").textContent = release.released_at.slice(0, 10);
      deliveryDownload.hidden = false;
      document.getElementById("deliverytracker-release-info").hidden = false;
      document.getElementById("deliverytracker-pending").hidden = true;
    })
    .catch(() => { /* Keep the preparation notice if release status cannot be read. */ });
}
